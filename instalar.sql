-- ---------- Reservas, ventas y bajas ----------
create or replace function public.recalcular_reservado()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op in ('UPDATE', 'DELETE') then
    update public.productos set reservado = coalesce((
      select sum(cantidad) from public.reservas
      where producto_id = old.producto_id and estado in ('pendiente', 'activa')), 0)
    where id = old.producto_id;
  end if;
  if tg_op in ('INSERT', 'UPDATE') then
    update public.productos set reservado = coalesce((
      select sum(cantidad) from public.reservas
      where producto_id = new.producto_id and estado in ('pendiente', 'activa')), 0)
    where id = new.producto_id;
  end if;
  return null;
end;
$$;

create trigger reservas_recalcular
after insert or update or delete on public.reservas
for each row execute function public.recalcular_reservado();

-- 6) Crear reserva: la usa el puesto (queda activa) y el cliente desde el catálogo (queda por confirmar)
create or replace function public.crear_reserva(
  pid bigint, cant integer, nombre text, tel text,
  pagado boolean default false, nota text default null)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  es_puesto boolean := coalesce(public.es_autorizado(), false);
  disp integer;
  rid bigint;
  tel_limpio text := regexp_replace(coalesce(tel, ''), '\D', '', 'g');
begin
  nombre := left(trim(coalesce(nombre, '')), 60);
  if nombre = '' then raise exception 'FALTA_NOMBRE'; end if;
  if length(tel_limpio) < 8 or length(tel_limpio) > 15 then raise exception 'TELEFONO_INVALIDO'; end if;
  if cant is null or cant < 1 or (not es_puesto and cant > 5) then raise exception 'CANTIDAD_INVALIDA'; end if;

  -- Freno anti abuso para reservas de clientes
  if not es_puesto and (
    select count(*) from public.reservas
    where telefono = tel_limpio and estado = 'pendiente' and created_at > now() - interval '1 day') >= 5 then
    raise exception 'DEMASIADAS_RESERVAS';
  end if;

  select cantidad - reservado into disp from public.productos where id = pid for update;
  if disp is null then raise exception 'NO_EXISTE'; end if;
  if disp < cant then raise exception 'NO_ALCANZA'; end if;

  insert into public.reservas (producto_id, cantidad, cliente, telefono, pagado, nota, estado, origen)
  values (pid, cant, nombre, tel_limpio, es_puesto and coalesce(pagado, false),
          left(nota, 200),
          case when es_puesto then 'activa' else 'pendiente' end,
          case when es_puesto then 'puesto' else 'cliente' end)
  returning id into rid;
  return rid;
end;
$$;
revoke all on function public.crear_reserva(bigint, integer, text, text, boolean, text) from public;
grant execute on function public.crear_reserva(bigint, integer, text, text, boolean, text) to anon, authenticated;

-- 7) Editar reserva (solo el puesto): cantidad, cliente, teléfono, pagó, nota
create or replace function public.editar_reserva(
  rid bigint, cant integer, nombre text, tel text, pagado boolean, nota text default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare r public.reservas; disp integer;
begin
  if not coalesce(public.es_autorizado(), false) then raise exception 'SIN_PERMISO'; end if;
  select * into r from public.reservas where id = rid for update;
  if r.id is null or r.estado not in ('pendiente', 'activa') then raise exception 'NO_EXISTE'; end if;
  select cantidad - reservado into disp from public.productos where id = r.producto_id for update;
  if cant < 1 or cant > disp + r.cantidad then raise exception 'NO_ALCANZA'; end if;
  update public.reservas set
    cantidad = cant,
    cliente = left(trim(nombre), 60),
    telefono = regexp_replace(tel, '\D', '', 'g'),
    pagado = coalesce(editar_reserva.pagado, false),
    nota = left(editar_reserva.nota, 200)
  where id = rid;
end;
$$;
revoke all on function public.editar_reserva(bigint, integer, text, text, boolean, text) from public, anon;
grant execute on function public.editar_reserva(bigint, integer, text, text, boolean, text) to authenticated;

-- 8) Entregar reserva = venta: descuenta del stock y queda registrada
create or replace function public.entregar_reserva(rid bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare r public.reservas; p public.productos;
begin
  if not coalesce(public.es_autorizado(), false) then raise exception 'SIN_PERMISO'; end if;
  select * into r from public.reservas where id = rid for update;
  if r.id is null or r.estado not in ('pendiente', 'activa') then raise exception 'NO_EXISTE'; end if;
  update public.reservas set estado = 'entregada', cerrada_at = now() where id = rid;
  update public.productos set cantidad = greatest(cantidad - r.cantidad, 0) where id = r.producto_id
  returning * into p;
  insert into public.movimientos (producto_id, titulo, tipo, cantidad, motivo, precio)
  values (p.id, p.titulo, 'venta', r.cantidad, 'Reserva de ' || r.cliente, p.precio);
end;
$$;
revoke all on function public.entregar_reserva(bigint) from public, anon;
grant execute on function public.entregar_reserva(bigint) to authenticated;

-- 9) Mover stock: venta o baja (delta negativo) e ingreso (delta positivo).
--    No deja vender ni dar de baja lo que está reservado.
create or replace function public.mover_stock(pid bigint, delta integer, tipo text, motivo text default null)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare p public.productos;
begin
  if not coalesce(public.es_autorizado(), false) then raise exception 'SIN_PERMISO'; end if;
  if delta = 0 or tipo not in ('venta', 'ajuste', 'ingreso') then raise exception 'CANTIDAD_INVALIDA'; end if;
  select * into p from public.productos where id = pid for update;
  if p.id is null then raise exception 'NO_EXISTE'; end if;
  if delta < 0 and -delta > p.cantidad - p.reservado then raise exception 'NO_ALCANZA'; end if;
  update public.productos set cantidad = cantidad + delta where id = pid returning * into p;
  insert into public.movimientos (producto_id, titulo, tipo, cantidad, motivo, precio)
  values (p.id, p.titulo, tipo, abs(delta), left(motivo, 80), p.precio);
  return p.cantidad;
end;
$$;
revoke all on function public.mover_stock(bigint, integer, text, text) from public, anon;
grant execute on function public.mover_stock(bigint, integer, text, text) to authenticated;

